# OPERADORES ARITMÉTICAS

a = 10
b = 3

print(f"Soma: {a + b}")                 # soma
print(f"Subtração: {a - b}")            # subtração
print(f"Multiplicação: {a * b}")        # multiplicação
print(f"Divisão: {a / b}")              # divisão (float)
print(f"Divisão inteira: {a // b}")     # divisão inteira (int)
print(f"Resto de divisão: {a % b}")     # resto de divisão (mod)
print(f"Potência: {a ** b}")            # Potência

# Ordem de prioridade
# 1º  **
# 2º  *  /  //  %
# 3º  +  -
