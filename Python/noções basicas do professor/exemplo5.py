# OPERADORES RELACIONAIS
a = 10
b = 20

print(a == b)           # igualdade
print(a != b)           # diferença
print(a > b)            # maior
print(a < b)            # menor
print(a >= b)           # maior ou igual
print(a <= b)           # menor ou igual

# OPERADORES LÓGICOS
print(a == b and b == 20)       # and
print(a == b or b == 20)        # or
print(not a == b)               # not
